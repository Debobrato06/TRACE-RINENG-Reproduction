"""Step 16 - write the result tables of the Method details / Method validation chapters and the
Supplementary Tables S1-S4 and Figures S1-S4 as Word files, from outputs/tables/*.csv (written by step 14).
  outputs/TRACE_main_tables.docx           Tables 2-5
  outputs/TRACE_Supplementary_Material.docx  Tables S1-S4 (S4a-d) and Figures S1-S4"""
import pandas as pd
from docx import Document
from docx.shared import Pt, Inches
import os
from docx.enum.section import WD_ORIENT

TD = 'outputs/tables/'


def fmt(v):
    if isinstance(v, float):
        return '' if pd.isna(v) else (f'{v:.3g}' if abs(v) < 1e-3 and v != 0 else f'{v:.3f}'.rstrip('0').rstrip('.') if v % 1 else f'{v:.0f}')
    return str(v)


def add_table(doc, caption, df, index=False):
    if index: df = df.reset_index()
    p = doc.add_paragraph(); r = p.add_run(caption); r.bold = True; r.font.size = Pt(10)
    t = doc.add_table(rows=1, cols=len(df.columns)); t.style = 'Table Grid'
    for j, c in enumerate(df.columns):
        t.rows[0].cells[j].text = str(c); t.rows[0].cells[j].paragraphs[0].runs[0].bold = True
    for _, row in df.iterrows():
        cells = t.add_row().cells
        for j, v in enumerate(row): cells[j].text = fmt(v)
    for row in t.rows:
        for c in row.cells:
            for par in c.paragraphs:
                for run in par.runs: run.font.size = Pt(8)
    doc.add_paragraph()


def new_doc(title):
    d = Document(); st = d.styles['Normal']; st.font.name = 'Times New Roman'; st.font.size = Pt(11)
    from docx.oxml.ns import qn
    z = d.settings.element.find(qn('w:zoom'))
    if z is not None and z.get(qn('w:percent')) is None: z.set(qn('w:percent'), '100')   # schema-valid settings.xml
    d.add_heading(title, level=1); return d


m = new_doc('TRACE - tables of the Method details and Method validation chapters')
add_table(m, 'Table 2. Audit classes, their decision rules and the claim each permits.', pd.read_csv(TD + 'Table2_classes.csv'))
add_table(m, 'Table 3. Default parameters and where each was stress-tested.', pd.read_csv(TD + 'Table3_parameters.csv'))
add_table(m, 'Table 4. Validation experiments.', pd.read_csv(TD + 'Table4_experiments.csv'))
add_table(m, 'Table 5. TRACE audit card for the four NASA cells: class with |r_res| for P, and (S0; Holm-adjusted p) for I and T.',
          pd.read_csv(TD + 'Table5_nasa_audit_card.csv'))
m.save('outputs/TRACE_main_tables.docx')

