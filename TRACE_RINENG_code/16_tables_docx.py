lo = pd.read_csv(TD + 'TableS1_nasa_loco.csv'); lo['RMSE'] = lo['RMSE'] * 1000; lo = lo.rename(columns={'RMSE': 'RMSE (mAh)'})
add_table(s, 'Table S1. NASA leave-one-cell-out results for every feature set, model and held-out cell.', lo)
add_table(s, 'Table S2. Size of the Ljung-Box exchangeability gate under AR(1) nulls and of the modified Mann-Kendall test.', pd.read_csv(TD + 'TableS2_test_size.csv'))
add_table(s, 'Table S3. Benchmark: share of 360 replicates in which each rule credits each planted type; last column = share TRACE v2 flags as D or P.',
          pd.read_csv(TD + 'TableS3_benchmark.csv'))
add_table(s, 'Table S4a. Re-classification of 6016 measured-feature verdicts under alternative determinism and proxy thresholds.', pd.read_csv(TD + 'TableS4a_threshold_sweep.csv'))
add_table(s, 'Table S4b. Sensitivity to the restatement threshold zeta.', pd.read_csv(TD + 'TableS4b_zeta_sweep.csv'))
add_table(s, 'Table S4c. Margin of the target-determinism threshold over the 378 measured cells.', pd.read_csv(TD + 'TableS4c_target_eta_margin.csv'))
add_table(s, 'Table S4d. p-value floor of the time-shift test in the NASA cells and confirmation by a circular-shift test (resolution 1/n).',
          pd.read_csv(TD + 'TableS4d_pfloor.csv'))
s.add_heading('Supplementary Figures S1-S4', level=1)
for f, cap in [('figS1_thresholds', 'Fig. S1. Threshold sensitivity: (a) share of verdicts changed under alternative determinism and proxy thresholds; (b) number of features classed P as the restatement threshold zeta varies.'),
               ('figS2_test_size', 'Fig. S2. Rejection rate under AR(1) nulls of the Ljung-Box exchangeability gate (n = 168 and 3000) and of the modified Mann-Kendall test; dotted line = 0.05.'),
               ('figS3_pfloor', 'Fig. S3. Holm-adjusted p-values of the NASA features under the default truncated time-shift test and a circular-shift test with resolution 1/n; dashed lines = attainable floor of the default test.'),
               ('figS4_external_proxy', 'Fig. S4. (a) Class shares of the 16 charge features by public dataset; (b) classes assigned to planted proxies as their noise grows (restatement boundary of S1).')]:
    p = 'figures/' + f + '.png'
    if os.path.exists(p):
        s.add_picture(p, width=Inches(6.3)); c = s.add_paragraph(cap); c.runs[0].font.size = Pt(9)
s.save('outputs/TRACE_Supplementary_Material.docx')
print('wrote outputs/TRACE_main_tables.docx and outputs/TRACE_Supplementary_Material.docx')
